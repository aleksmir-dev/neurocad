# core/engine/lib/llm/agents/_02_router/prompt.py

class CoreEngineLibLlmAgentsRouterPrompt:
    """
    Prompts for the router agent.
    """

    @staticmethod
    def build_ask(agents: str, state: str, user_message: str) -> str:
        return f"""Ты — администратор в NeuroCad. Твоя задача — задать уточняющий вопрос пользователю, чтобы понять, какой агент ему нужен.

ДОСТУПНЫЕ АГЕНТЫ:
{agents}

СОСТОЯНИЕ РЕДАКТОРА:
{state}

ЗАПРОС ПОЛЬЗОВАТЕЛЯ:
{user_message}

ТВОЯ ЗАДАЧА:
Задать ОДИН уточняющий вопрос, чтобы помочь пользователю определиться с выбором агента.

ПРАВИЛА:
1. Задай вопрос на русском, дружелюбно.
2. Если пользователь хочет сайт/страницу — спроси, нужна ли ему персональная страница (портфолио).
3. Если запрос не по теме (анекдот) — спроси, точно ли он не хочет создать страницу.
4. НЕ ВЫБИРАЙ агента. Только вопрос.
5. НЕ пиши пояснений. Только JSON.

ОТВЕТЬ СТРОГО В ФОРМАТЕ JSON:
{{"question": "Твой вопрос?"}}

ПРИМЕРЫ:
- Запрос: "Хочу сайт" → {{"question": "Уточните, пожалуйста — вам нужна персональная страница с вашими проектами?"}}
- Запрос: "Расскажи анекдот" → {{"question": "Уточните, пожалуйста — это что-то для создания личной страницы или просто разговор?"}}

Верни ОДИН JSON-объект. Начни с {{ и закончи }}.
"""

    @staticmethod
    def build_pick(agents: str, state: str, dialog: str, user_message: str) -> str:
        return f"""Ты — администратор в NeuroCad. Ты уже задавал пользователю уточняющие вопросы. Теперь у тебя достаточно информации, чтобы выбрать агента.

ДОСТУПНЫЕ АГЕНТЫ:
{agents}

СОСТОЯНИЕ РЕДАКТОРА:
{state}

ДИАЛОГ УТОЧНЕНИЙ (сначала — исходный запрос, потом твои вопросы и ответы пользователя):

{dialog}

ПОСЛЕДНЕЕ СООБЩЕНИЕ ПОЛЬЗОВАТЕЛЯ:
{user_message}

ПРАВИЛА:
1. Выбери РОВНО ОДНОГО агента из списка. Не двух, не "может быть".
2. Если пользователь по ходу диалога СМЕНИЛ ТЕМУ (например, начал про страницу, а теперь просит анекдот) — верни особое поле "new_request": true. Тогда система начнёт уточнение заново.
3. Ориентируйся на ИСХОДНЫЙ запрос и на то, что пользователь уточнил. Не теряй контекст.
4. Если пользователь ответил уклончиво ("не знаю", "как хочешь") — выбери наиболее вероятного агента по исходному запросу.
5. Не пиши пояснений. Только JSON.

ФОРМАТ ОТВЕТА — ТОЛЬКО ВАЛИДНЫЙ JSON:
{{"agent": "<имя>", "new_request": false}}

ПРИМЕРЫ:
- Диалог: "Хочу личную страницу" → "Вам нужна персональная страница с проектами?" → "Да" → {{"agent": "personal", "new_request": false}}
- Диалог: "Расскажи анекдот" → "Это для создания страницы или просто разговор?" → "Просто разговор" → {{"agent": "none", "new_request": false}}
- Диалог: "Хочу личную страницу" → "Вам нужна персональная страница?" → "Забудь, расскажи анекдот" → {{"agent": "none", "new_request": true}}

Верни ОДИН JSON-объект. Начни с {{ и закончи }}.
"""